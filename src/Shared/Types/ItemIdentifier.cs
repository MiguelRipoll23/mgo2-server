/// <summary>
/// The protocol's item table, id for id: a row's position is the id, which is the byte
/// a damage record carries as its weapon and the byte a world-object record carries as
/// its item.
/// </summary>
/// <remarks>
/// <para>
/// <b>Ported from the replay console's <c>ITEM_NAMES</c></b>
/// (<c>.gametools/replay-console/rpdt.js</c>), all 297 rows, which is the list the
/// console's own parser validates a record's item byte against. It supersedes the
/// question of what an id above 140 means: <see cref="WeaponIdentifier"/> is the ELF's
/// 141-row weapon table and stops where the weapons stop, while this table continues
/// through the pickups, the gadgets and the faces.
/// </para>
/// <para>
/// The names are the console's strings with the spelling normalised to a C# identifier,
/// and a repeated string keeps its first spelling bare and every later one suffixed with
/// its own id, so no two members collide and each traces back to one row. Measured on
/// the wire: <c>0x18</c> <see cref="M4"/>, <c>0x19</c> <see cref="AK102"/>, <c>0x34</c>
/// <see cref="Grenade"/>, <c>0x02</c> <see cref="StKnife"/>, <c>0x17</c>
/// <see cref="Skorpion"/>, <c>0x07</c> <see cref="Fiveseven"/> — see
/// <c>docs/protocol/ITEM_AND_DAMAGE_TABLE.md</c>.
/// </para>
/// <para>
/// <b>Wider than the byte the wire carries.</b> The array runs to 297 rows and the record's
/// item field is one byte, so ids <c>0</c>–<c>255</c> are the ones a record can name and
/// <c>256</c>–<c>296</c> — the <c>WP_Bul*</c> bullet rows — are reachable only where a wider
/// field carries them. The enum is <c>ushort</c> for that reason: narrowing it would mean
/// dropping rows the table holds, which is the one thing this file exists not to do.
/// </para>
/// <para>
/// <b><c>0xff</c> is a row here.</b> <see cref="WpBulVss"/> holds 255, where
/// <see cref="WeaponIdentifier.Unreported"/> is documented as a value no table row carries.
