-- Repair for deployment databases that predate the instructor feature
-- (commit b1f032e). DatabaseInitializer used EnsureCreatedAsync, which does
-- nothing on an existing database, so these tables were never created there
-- and the connect burst died mid-flight with 42P01.
--
-- Generated from the EF model with the migrations differ + SQL generator
-- (tools/SchemaDdl), so it matches a fresh database byte for byte.
-- Purely additive; re-running is a no-op thanks to IF NOT EXISTS.

BEGIN;

CREATE TABLE IF NOT EXISTS character_training_times (
    character_id integer NOT NULL,
    training_mode_seconds bigint NOT NULL,
    instructor_seconds bigint NOT NULL,
    student_seconds bigint NOT NULL,
    CONSTRAINT "PK_character_training_times" PRIMARY KEY (character_id)
);

CREATE TABLE IF NOT EXISTS characters_instructors (
    character_id integer NOT NULL,
    instructor_character_id integer NOT NULL,
    instructor_name character varying(16) NOT NULL,
    generation integer NOT NULL,
    rating smallint NOT NULL,
    graduated_at timestamp without time zone NOT NULL,
    instructor_skill_awarded_at timestamp without time zone,
    CONSTRAINT "PK_characters_instructors" PRIMARY KEY (character_id),
    CONSTRAINT "FK_characters_instructors_characters_character_id" FOREIGN KEY (character_id) REFERENCES characters (id) ON DELETE CASCADE,
    CONSTRAINT "FK_characters_instructors_characters_instructor_character_id" FOREIGN KEY (instructor_character_id) REFERENCES characters (id)
);

CREATE TABLE IF NOT EXISTS instructor_reviews (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    instructor_character_id integer NOT NULL,
    student_character_id integer NOT NULL,
    rating smallint NOT NULL,
    recognised boolean NOT NULL,
    answer_byte smallint NOT NULL,
    reviewed_at timestamp with time zone NOT NULL,
    CONSTRAINT "PK_instructor_reviews" PRIMARY KEY (id),
    CONSTRAINT "FK_instructor_reviews_characters_instructor_character_id" FOREIGN KEY (instructor_character_id) REFERENCES characters (id) ON DELETE CASCADE,
    CONSTRAINT "FK_instructor_reviews_characters_student_character_id" FOREIGN KEY (student_character_id) REFERENCES characters (id)
);

CREATE INDEX IF NOT EXISTS "IX_characters_instructors_instructor_character_id" ON characters_instructors (instructor_character_id);

CREATE INDEX IF NOT EXISTS "IX_instructor_reviews_instructor_character_id_reviewed_at" ON instructor_reviews (instructor_character_id, reviewed_at);

CREATE INDEX IF NOT EXISTS "IX_instructor_reviews_student_character_id" ON instructor_reviews (student_character_id);

COMMIT;
